async function generateAIProductComparison(query, openResult = true) {
  const list = document.getElementById('autocompleteList');
  const dropdown = document.getElementById('autocompleteDropdown');
  const showStatus = message => {
    onlineSearchAttempts.set(query.toLowerCase(), { at: Date.now(), message });
    dropdown.classList.remove('hidden');
    list.innerHTML = '<div class="p-4 text-xs text-slate-600" role="status">' + escapeHtml(message) + '</div>';
  };
  if (onlineSearchAttempts.size > 100) onlineSearchAttempts.delete(onlineSearchAttempts.keys().next().value);
  if (location.protocol === 'file:') {
    showStatus('Internet qidiruvi uchun saytni server orqali oching: http://127.0.0.1:3000');
    return;
  }
  onlineSearchController?.abort();
  const controller = new AbortController();
  onlineSearchController = controller;
  showStatus('Internetdan narxlar va to‘lov usullari tekshirilmoqda...');
  try {
    const response = await fetch('/api/search', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ query }), signal: AbortSignal.any([controller.signal, AbortSignal.timeout(130000)]) });
    const data = await response.json();
    if (controller.signal.aborted || document.getElementById('searchInput').value.trim().toLowerCase() !== query.trim().toLowerCase()) return;
    if (!response.ok) throw new Error(data.error || 'Internet qidiruvi bajarilmadi.');
    if (!data.products?.length) { showStatus('Tasdiqlangan narxli taklif topilmadi. Mahsulot modeli yoki nomini aniqlashtiring.'); return; }
    await refreshCatalog(false);
    if (controller.signal.aborted || document.getElementById('searchInput').value.trim().toLowerCase() !== query.trim().toLowerCase()) return;
    for (const p of data.products) {
      const index = productsDatabase.findIndex(existing => existing.id === p.id);
      if (index < 0) productsDatabase.push(p); else productsDatabase[index] = p;
    }
    productsDatabase.sort((a, b) => Number(Boolean(b.bankTransfer)) - Number(Boolean(a.bankTransfer)));
    renderHomeProducts(homeCategory);
    if (document.getElementById('catalogGrid')) filterCatalogCategory(catalogCategory);
    if (openResult) { hideAutocomplete(); displayComparison(data.products[0]); }
    else handleAutocomplete();
  } catch (error) {
    if (!controller.signal.aborted && document.getElementById('searchInput').value.trim().toLowerCase() === query.trim().toLowerCase()) showStatus(error.name === 'TimeoutError' ? 'Qidiruv vaqti tugadi. Keyinroq qayta urining.' : error.message);
  }
}

