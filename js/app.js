function handleAutocomplete() {
  clearTimeout(onlineSearchTimer);
  const val = document.getElementById("searchInput").value.trim().toLowerCase();
  const dropdown = document.getElementById("autocompleteDropdown");
  const list = document.getElementById("autocompleteList");

  if (!val) {
    dropdown.classList.add("hidden");
    return;
  }

  const matches = productsDatabase.filter(
    (p) => p.name.toLowerCase().includes(val) || p.keywords.some((k) => k.toLowerCase().includes(val))
  );

  if (matches.length === 0) {
    list.innerHTML = `
      <div class="p-4 text-center text-xs text-slate-500">
          <i class="fa-solid fa-magnifying-glass text-slate-300 text-lg mb-1 block"></i>
          <span>"${escapeHtml(val)}" uchun internetdan takliflar qidiriladi...</span>
      </div>
    `;
    const previousAttempt = onlineSearchAttempts.get(val);
    if (previousAttempt && Date.now() - previousAttempt.at <= 60000) list.innerHTML = '<div class="p-4 text-xs text-slate-600" role="status">' + escapeHtml(previousAttempt.message) + '</div>';
    if (val.length >= 3 && val.length <= 160 && Date.now() - (previousAttempt?.at || 0) > 60000) {
      onlineSearchTimer = setTimeout(() => generateAIProductComparison(val, false), 1000);
    }
  } else {
    list.innerHTML = matches
      .map(
        (p) => `
          <div onclick="selectProduct('${p.id}')" class="p-3 hover:bg-indigo-50/60 cursor-pointer transition flex items-center justify-between group">
              <div class="flex items-center gap-3">
                  <img src="${p.image}" class="w-10 h-10 object-cover rounded-lg border border-slate-200">
                  <div>
                      <div class="text-sm font-bold text-slate-800 group-hover:text-indigo-600">${highlightMatch(p.name, val)}</div>
                      <div class="text-[11px] text-slate-400"><i class="fa-solid fa-building text-[10px]"></i> ${escapeHtml(p.supplier)}</div>
                  </div>
              </div>
              <div class="text-right">
                  <div class="text-xs font-black text-emerald-600">${p.unitPrice.toLocaleString()} UZS</div>
                  <span class="text-[10px] text-slate-400">Optom narx</span>
              </div>
          </div>
        `
      )
      .join("");
  }

  dropdown.classList.remove("hidden");
}

function highlightMatch(text, query) {
  const index = text.toLowerCase().indexOf(query.toLowerCase());
  if (index < 0 || !query) return escapeHtml(text);
  return escapeHtml(text.slice(0, index)) + '<span class="bg-amber-200 text-slate-900 rounded-sm px-0.5">' + escapeHtml(text.slice(index, index + query.length)) + '</span>' + escapeHtml(text.slice(index + query.length));
}

