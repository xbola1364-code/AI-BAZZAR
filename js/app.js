function updateChart(newData, labels) {
  if (chartInstance) {
    chartInstance.data.datasets[0].data = newData;
    if (labels) chartInstance.data.labels = labels.map(label => label.includes('T') ? new Date(label).toLocaleString('uz-UZ', { month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit' }) : label);
    chartInstance.update();

    const min = Math.min(...newData).toLocaleString();
    const max = Math.max(...newData).toLocaleString();
    document.getElementById("chartMinMax").innerText = `Min: ${min} UZS | Max: ${max} UZS`;
  }
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
}

function sourceLink(url, label) {
  if (!url) return '';
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== 'https:' || parsed.username || parsed.password) return '';
    return '<a class="text-xs text-indigo-600 underline mr-3" target="_blank" rel="noopener noreferrer" href="' + escapeHtml(parsed.href) + '">' + escapeHtml(label) + '</a>';
  } catch { return ''; }
}

async function refreshCatalog(render = true) {
  if (location.protocol === 'file:' || catalogLoading) return;
  catalogLoading = true;
  try {
    const response = await fetch('/api/catalog', { signal: AbortSignal.timeout(10000), cache: 'no-store' });
    if (!response.ok) throw new Error(`Catalog HTTP ${response.status}`);
    const data = await response.json();
    if (!Array.isArray(data.products) || !Array.isArray(data.markets) || !Array.isArray(data.ticker)) throw new Error('Invalid catalog');
    productsDatabase.splice(0, productsDatabase.length, ...data.products.filter(p => p.available !== false));
    marketsDatabase.splice(0, marketsDatabase.length, ...data.markets);
    tickerData.splice(0, tickerData.length, ...data.ticker);
    catalogConnected = true;
    if (!render) return;
    initTicker();
    renderHomeProducts(homeCategory);
    if (document.getElementById('catalogGrid')) filterCatalogCategory(catalogCategory);
    const active = productsDatabase.find(p => p.id === activeProductId);
    if (active && !document.getElementById('resultsSection').classList.contains('hidden')) {
      displayComparison(active, false);
    } else if (activeProductId && !active) {
      document.getElementById('resultsSection').classList.add('hidden');
      document.getElementById('analyticsSection').classList.add('hidden');
      document.getElementById('homeSection').classList.remove('hidden');
      activeProductId = null;
    }
    if (!document.getElementById('autocompleteDropdown').classList.contains('hidden')) handleAutocomplete();
  } catch (error) {
    console.warn('Catalog refresh failed; retaining the last loaded data.', error.message);
  } finally { catalogLoading = false; }
}
